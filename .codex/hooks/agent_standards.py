#!/usr/bin/env python3
"""Codex lifecycle adapter for canonical project and enabled-plugin hooks.

Hook protocol entry point: JSON on stdin, hook response JSON on stdout. Detailed
execution evidence lives under the checkout's tmp/logs/codex-hooks/ directory.
This file is generated by agent-standards; change its template there.
"""
from __future__ import annotations

import datetime
import fnmatch
import fcntl
import hashlib
import importlib.util
import json
import os
import pathlib
import re
import shlex
import signal
import subprocess
import sys
import time
import uuid


def translated(text):
    """Keep guidance meaningful without referring to Claude-only tool calls."""
    text = re.sub(r"(?:with|using) the Skill tool\s*\(`([^`]+)`\)",
                  lambda match: "by reading .agents/skills/" + match[1].split(":")[-1] + "/SKILL.md", text)
    return text.replace("ToolSearch", "native MCP tool discovery")


def patch_inputs(patch, root):
    """Expose each touched file, including rename destinations, before mutation."""
    edits = []
    current = None
    for line in patch.splitlines():
        match = re.match(r"^\*\*\* (Add|Update|Delete) File: (.+)$", line)
        if match:
            operation, path = match.groups()
            current = {"file_path": str((root / path).resolve()), "content": "", "new_string": "", "old_string": ""}
            edits.append(("Write" if operation == "Add" else "Edit", current))
        elif line.startswith("*** Move to: ") and current is not None:
            moved = dict(current, file_path=str((root / line[13:]).resolve()))
            edits.append(("Write", moved))
            current = moved
        elif current is not None and line.startswith("+"):
            current["content"] += line[1:] + "\n"
            current["new_string"] += line[1:] + "\n"
        elif current is not None and line.startswith("-"):
            current["old_string"] += line[1:] + "\n"
    return edits


def tool_events(event, root):
    name = event.get("tool_name", "")
    supplied = event.get("tool_input") or {}
    if name in {"apply_patch", "functions.apply_patch"}:
        patch = supplied.get("command", supplied.get("patch", "")) if isinstance(supplied, dict) else supplied
        cwd = pathlib.Path(event.get("cwd") or root)
        return [dict(event, tool_name=kind, tool_input=data) for kind, data in patch_inputs(patch, cwd)]
    if name in {"exec_command", "shell_command", "shell"}:
        supplied = dict(supplied)
        supplied["command"] = supplied.get("command", supplied.get("cmd", ""))
        return [dict(event, tool_name="Bash", tool_input=supplied)]
    return [event]


def file_paths(event, root):
    supplied = event.get("tool_input") or {}
    paths = []
    if supplied.get("file_path"):
        paths.append(root / supplied["file_path"])
    if event.get("tool_name") == "Bash":
        try:
            words = shlex.split(supplied.get("command", ""))
        except ValueError:
            words = []
        for word in words:
            path = pathlib.Path(event.get("cwd") or root) / word
            if path.is_file():
                paths.append(path)
    for key in ("path", "filePath", "file", "file_path"):
        if isinstance(supplied.get(key), str):
            paths.append(root / supplied[key])
    return tuple(dict.fromkeys(path.resolve() for path in paths))


def glob_matches(path, pattern):
    # Claude path rules use brace alternatives and root-recursive ** globs.
    brace = re.search(r"\{([^{}]+)\}", pattern)
    if brace:
        return any(glob_matches(path, pattern[:brace.start()] + value + pattern[brace.end():]) for value in brace[1].split(","))
    def segments(values, patterns):
        if not patterns:
            return not values
        if patterns[0] == "**":
            return any(segments(values[index:], patterns[1:]) for index in range(len(values) + 1))
        return bool(values) and fnmatch.fnmatchcase(values[0], patterns[0]) and segments(values[1:], patterns[1:])
    return segments(path.split("/"), pattern.split("/"))


def rule_matches(path, patterns):
    positive = [pattern for pattern in patterns if not pattern.startswith("!")]
    excluded = [pattern[1:] for pattern in patterns if pattern.startswith("!")]
    return (not positive or any(glob_matches(path, pattern) for pattern in positive)) and not any(glob_matches(path, pattern) for pattern in excluded)


def reminders(root, runtime, event, events):
    contexts = []
    key = hashlib.sha256((str(event.get("session_id", "unknown")) + str(event.get("agent_id", ""))).encode()).hexdigest()
    folder = root / "tmp/codex-guidance" / key
    if event.get("hook_event_name") in {"PostCompact", "SessionStart"} and event.get("source") == "compact":
        for marker in folder.glob("*"):
            marker.unlink()
    folder.mkdir(parents=True, exist_ok=True)
    paths = tuple(dict.fromkeys(path for item in events for path in file_paths(item, root)))
    for rule in runtime["rules"]:
        matched = False
        for path in paths:
            try:
                relative = path.relative_to(root).as_posix()
            except ValueError:
                continue
            if rule_matches(relative, rule["paths"]):
                matched = True
        if matched:
            marker = folder / hashlib.sha256(rule["source"].encode()).hexdigest()
            if not marker.exists():
                contexts.append("Project rule " + rule["source"] + ":\n" + rule["body"])
                marker.touch()
    predicates = {"auditing": "handles_errors", "web-factoring": "browser_code",
                  "browser-testing": "browser_test", "ios-ui-testing": "ui_test"}
    for plugin, relative in runtime["plugins"].items():
        name = plugin.split("@", 1)[0]
        if name not in predicates or (folder / name).exists():
            continue
        script = root / relative / "scripts/nudge.py"
        spec = importlib.util.spec_from_file_location("codex_nudge_" + name.replace("-", "_"), script)
        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)
        predicate = getattr(module, predicates[name])
        if any(predicate(path, root) if name == "web-factoring" else predicate(path) for path in paths):
            contexts.append(translated(module.NUDGE))
            (folder / name).touch()
    return contexts


def run_command(command, payload, root, plugin_root, timeout, audit):
    # These environment keys are Claude's hook transport contract, not application
    # configuration. Keep the original command and payload otherwise intact.
    environment = dict(os.environ, CLAUDE_PROJECT_DIR=str(root))
    if plugin_root:
        environment["CLAUDE_PLUGIN_ROOT"] = str(plugin_root)
    started = time.monotonic()
    process = subprocess.Popen(command, shell=True, cwd=root, env=environment,
                               stdin=subprocess.PIPE, stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                               text=True, start_new_session=True)
    timed_out = False
    try:
        stdout, stderr = process.communicate(json.dumps(payload), timeout=timeout)
    except subprocess.TimeoutExpired:
        timed_out = True
        os.killpg(process.pid, signal.SIGKILL)
        stdout, stderr = process.communicate()
    # Never log the original tool input, command arguments or secret contents.
    audit("hook.command.finished", status=process.returncode, timeout=timed_out,
          duration_seconds=time.monotonic()-started)
    if timed_out:
        raise TimeoutError(f"canonical hook exceeded {timeout}s")
    return process.returncode, stdout, stderr


def security_guidance(root, runtime, event, events, audit, review):
    """Use the enabled provider's pure rules/prompts with native Codex review.

    Claude's SDK installer and credential lookup are not a Codex runtime. Keep
    pattern checks in-process and run the same investigation/refutation guidance
    in a bounded native session. Only recursive security review is suppressed;
    the child inherits project permissions and all canonical policy hooks.
    """
    relative = runtime["plugins"].get("security-guidance@claude-plugins-official")
    if relative is None:
        return [], False
    session = str(event.get("session_id", "unknown"))
    if re.fullmatch(r"[a-zA-Z0-9_-]+", session) and (root / "tmp/codex-security/reviewer-sessions" / session).is_file():
        return [], False
    contexts = []
    paths = tuple(dict.fromkeys(path for item in events for path in file_paths(item, root)))
    event_name = event.get("hook_event_name")
    key = hashlib.sha256(str(event.get("session_id", "unknown")).encode()).hexdigest()
    state = root / "tmp/codex-security" / key
    state.mkdir(parents=True, exist_ok=True)
    changed = state / "changed.json"
    tracked = json.loads(changed.read_text()) if changed.is_file() else {}
    baseline_path = state / "baseline.json"
    if not baseline_path.is_file():
        write_json(baseline_path, repository_snapshot(root))
    baseline = json.loads(baseline_path.read_text())
    if event_name == "PostToolUse":
        module_path = root / relative / "hooks/patterns.py"
        spec = importlib.util.spec_from_file_location("native_security_patterns", module_path)
        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)
        edits = [item for item in events if item.get("tool_name") in {"Edit", "Write", "MultiEdit"}]
        for item in edits:
            for path in file_paths(item, root):
                if root not in path.parents:
                    continue
                if not path.is_file():
                    tracked[str(path)] = "deleted"
                    continue
                text = path.read_text(errors="replace")
                tracked[str(path)] = hashlib.sha256(text.encode()).hexdigest()
                for pattern in module.SECURITY_PATTERNS:
                    try:
                        relative_path = path.relative_to(root).as_posix()
                        if "path_filter" in pattern and not pattern["path_filter"](relative_path):
                            continue
                        hit = ("path_check" in pattern and pattern["path_check"](relative_path)) or any(value in text for value in pattern.get("substrings", [])) or ("regex" in pattern and re.search(pattern["regex"], text))
                        if hit:
                            contexts.append(pattern["reminder"])
                    except (ValueError, re.error):
                        continue
        write_json(changed, tracked)
    commit_or_push = any(item.get("tool_name") == "Bash" and re.search(r"\bgit\b[^\n;]*\b(commit|push)\b", item.get("tool_input", {}).get("command", "")) for item in events)
    if event_name != "Stop" and not (event_name == "PostToolUse" and commit_or_push):
        return contexts, False
    current = repository_snapshot(root)
    for relative in set(baseline["files"]) | set(current["files"]):
        if baseline["files"].get(relative) != current["files"].get(relative):
            tracked[str(root / relative)] = current["files"].get(relative, "deleted")
    # A fix may restore a path to its original content. Compare current content,
    # never a stale post-edit digest, when deciding whether another review is due.
    tracked = {path: current["files"].get(str(pathlib.Path(path).relative_to(root)), "deleted") for path in tracked}
    write_json(changed, tracked)
    if not tracked:
        return contexts, False
    fingerprint = hashlib.sha256(json.dumps(tracked, sort_keys=True).encode()).hexdigest()
    reviewed = state / "reviewed.json"
    if reviewed.is_file():
        previous = json.loads(reviewed.read_text())
        if previous.get("fingerprint") == fingerprint:
            findings = previous["findings"]
            acknowledgement = state / "acknowledgement.json"
            if acknowledgement.is_file():
                accepted = json.loads(acknowledgement.read_text())
                if accepted.get("fingerprint") == fingerprint and accepted.get("rationale", "").strip():
                    audit("security.review.acknowledged", fingerprint=fingerprint)
                    return contexts, False
            if findings:
                return contexts + [security_findings(findings, fingerprint, state)], True
            return contexts, False
    instructions = (root / ".codex/agent-standards/security-review.md").read_text()
    instructions += "\n\nReview only this session's changed files and relevant callers: " + json.dumps(list(tracked))
    instructions += "\nThe session started at Git HEAD " + baseline["head"] + ". Compare against that revision, including working-tree edits and deleted files; commits made during this session remain in scope. The initial snapshot excludes pre-existing changes that stayed unchanged."
    instructions += "\nRead the files and git diff. Do not edit, commit, install dependencies, run tests or delegate. Return only substantive exploitable findings after self-refutation, with file and line evidence. Empty findings means no substantiated vulnerability. Do not report cosmetic issues.\n"
    if review is None:
        raise RuntimeError("native review collaborator was not supplied")
    result = review(state, instructions, fingerprint)
    fresh = repository_snapshot(root)
    if any(fresh["files"].get(str(pathlib.Path(path).relative_to(root)), "deleted") != version for path, version in tracked.items()):
        return contexts + ["Files changed while the native security review ran. Its result is stale; review the current content before completing."], True
    findings = result["findings"]
    write_json(reviewed, {"fingerprint": fingerprint, "findings": findings})
    if findings:
        contexts.append(security_findings(findings, fingerprint, state))
    return contexts, bool(findings)


def native_review(root, state, instructions, audit):
    """Create a marked native session before starting its model turn.

    The marker has exactly the session lifetime and only disables this adapter's
    recursive security review. Project denials and other lifecycle hooks remain.
    """
    from rpc_client import AppServer
    marker = None
    started = time.monotonic()
    with (state / "review.log").open("w") as log, (state / "review.stderr.log").open("w") as errors:
        try:
            with AppServer(root, errors) as server:
                thread = server.request("thread/start", {"cwd": str(root), "ephemeral": True, "approvalPolicy": "never"})["thread"]["id"]
                uuid.UUID(thread)
                marker = root / "tmp/codex-security/reviewer-sessions" / thread
                marker.parent.mkdir(parents=True, exist_ok=True)
                write_json(marker, {"owner_pid": os.getpid()})
                audit("security.review.started", reviewer_session=thread)
                pending = []
                server.request("turn/start", {"threadId": thread, "input": [{"type": "text", "text": instructions, "text_elements": []}],
                               "outputSchema": json.loads((root / ".codex/agent-standards/security-review.schema.json").read_text())}, notifications=pending)
                deadline = time.monotonic() + 300
                answer = None
                while time.monotonic() < deadline:
                    message = pending.pop(0) if pending else server.receive(max(0, deadline-time.monotonic()))
                    if "id" in message and "method" in message:
                        server.send({"id": message["id"], "error": {"code": -32601, "message": "review cannot approve or request human input"}})
                        continue
                    method = message.get("method")
                    params = message.get("params", {})
                    log.write(json.dumps({"event": method}) + "\n");log.flush()
                    if method == "item/completed" and params.get("item", {}).get("type") == "agentMessage":
                        answer = params["item"]["text"]
                    if method == "turn/completed":
                        turn = params["turn"]
                        if turn["status"] != "completed" or answer is None:
                            raise RuntimeError(f"native security review failed: {turn.get('error') or turn['status']}")
                        result = json.loads(answer)
                        write_json(state / "review.json", result)
                        audit("security.review.finished", status=0, reviewer_session=thread, duration_seconds=time.monotonic()-started)
                        return result
                raise TimeoutError("native security review exceeded 300s")
        finally:
            if marker is not None:
                marker.unlink(missing_ok=True)


def security_findings(findings, fingerprint, state):
    return ("Native security review findings (resolve before completing):\n" + "\n".join(findings)
            + "\nIf a finding is a false positive, record concrete refuting evidence in " + str(state / "acknowledgement.json")
            + ' as {"fingerprint":' + json.dumps(fingerprint) + ',"rationale":"specific evidence"}. An unchanged retry does not clear pending findings.')


def write_json(path, value):
    temporary = path.with_name(path.name + ".tmp")
    temporary.write_text(json.dumps(value))
    temporary.replace(path)


def repository_snapshot(root):
    """Capture worktree content without changing Git or following secret symlinks."""
    listing = subprocess.run(["git", "ls-files", "-co", "--exclude-standard", "-z"], cwd=root,
                             capture_output=True, check=True, timeout=15)
    files = {}
    for name in listing.stdout.decode().split("\0"):
        if not name:
            continue
        path = root / name
        digest = hashlib.sha256()
        if path.is_symlink():
            digest.update(str(path.readlink()).encode())
        elif path.is_file():
            with path.open("rb") as stream:
                for block in iter(lambda: stream.read(1024 * 1024), b""):
                    digest.update(block)
        else:
            continue
        files[name] = digest.hexdigest()
    head = subprocess.run(["git", "rev-parse", "--verify", "HEAD"], cwd=root, capture_output=True, text=True, timeout=5)
    return {"head": head.stdout.strip() if head.returncode == 0 else "unborn (all files are new)", "files": files}


def dispatch(root, runtime, event, audit, review=None):
    event = dict(event)
    event_name = event.get("hook_event_name", "")
    if event_name == "PostCompact":
        event.update(hook_event_name="SessionStart", source="compact")
        event_name = "SessionStart"
    events = tool_events(event, root)
    contexts = reminders(root, runtime, event, events) if event_name in {"PreToolUse", "PostToolUse", "SessionStart"} else []
    decision = None
    security_contexts, block = security_guidance(root, runtime, event, events, audit, review)
    contexts.extend(security_contexts)
    for origin, definitions in runtime["hooks"].items():
        plugin_root = root / runtime["plugins"][origin] if origin != "project" else None
        # Nudge scripts use Claude transcripts and global temp markers. The
        # native adapter above reuses their predicates and text with root tmp.
        if origin.split("@", 1)[0] in {"auditing", "web-factoring", "browser-testing", "ios-ui-testing"}:
            continue
        if origin == "security-guidance@claude-plugins-official":
            continue
        for payload in events:
            canonical_event = event_name
            response = event.get("tool_response") or {}
            if event_name == "PostToolUse" and (event.get("error") or (isinstance(response, dict) and response.get("isError"))):
                canonical_event = "PostToolUseFailure"
            for group in definitions.get(canonical_event, []):
                matcher = group.get("matcher")
                subject = payload.get("tool_name", "") if "ToolUse" in canonical_event else payload.get("source", "")
                if matcher and not re.search(matcher, subject):
                    continue
                for handler in group.get("hooks", []):
                    condition = handler.get("if")
                    if condition:
                        match = re.fullmatch(r"(\w+)\((.*)\)", condition)
                        if not match or payload.get("tool_name") != match[1] or not fnmatch.fnmatchcase(payload.get("tool_input", {}).get("command", ""), match[2]):
                            continue
                    status, stdout, stderr = run_command(handler["command"], dict(payload, hook_event_name=canonical_event), root, plugin_root,
                                                         handler.get("timeout", 600), audit)
                    try:
                        answer = json.loads(stdout) if stdout.strip() else {}
                    except ValueError:
                        answer = {}
                        if stdout.strip():
                            contexts.append(translated(stdout.strip()))
                    output = answer.get("hookSpecificOutput", {})
                    if answer.get("systemMessage"):
                        contexts.append(translated(answer["systemMessage"]))
                    if output.get("additionalContext"):
                        contexts.append(translated(output["additionalContext"]))
                    permission = output.get("permissionDecision")
                    if permission == "deny":
                        # Never turn a Claude allow result into a Codex allow. An "ask" is
                        # ignored: agents here never ask, so it is no decision at all.
                        if decision is None or permission == "deny":
                            decision = (permission, output.get("permissionDecisionReason", "canonical project policy"))
                    if answer.get("decision") == "block" or status == 2:
                        block = True
                        contexts.append(translated(answer.get("reason", stderr or "Canonical hook blocked this operation.")))
                    elif status:
                        contexts.append(f"Canonical hook {origin} failed ({status}): " + translated(stderr or stdout))
    result = {"hookSpecificOutput": {"hookEventName": event.get("hook_event_name"), "additionalContext": "\n\n".join(contexts)}}
    if decision:
        permission, reason = decision
        result["hookSpecificOutput"].update(permissionDecision=permission, permissionDecisionReason=reason)
    if block:
        result.update(decision="block", reason="\n\n".join(contexts))
    return result


def main():
    root = pathlib.Path(__file__).resolve().parents[2]
    log_dir = root / "tmp/logs/codex-hooks"
    log_dir.mkdir(parents=True, exist_ok=True)
    log_path = log_dir / (datetime.datetime.now(datetime.timezone.utc).strftime("%Y%m%d") + ".jsonl")
    with log_path.open("a") as log:
        def audit(event, **data):
            log.write(json.dumps({"timestamp": datetime.datetime.now(datetime.timezone.utc).isoformat(), "severity": "INFO", "event": event, **data}) + "\n")
            log.flush()
        try:
            event = json.load(sys.stdin)
            runtime = json.loads((root / ".codex/agent-standards/runtime.json").read_text())
            with (log_dir / "dispatch.lock").open("a") as lock:
                fcntl.flock(lock, fcntl.LOCK_EX)
                with (log_dir / "security-review.lock").open("a") as review_lock:
                    review_held = False
                    def review(state, instructions, fingerprint):
                        nonlocal review_held
                        fcntl.flock(lock, fcntl.LOCK_UN)
                        try:
                            fcntl.flock(review_lock, fcntl.LOCK_EX)
                            review_held = True
                            cached = state / "reviewed.json"
                            if cached.is_file():
                                previous = json.loads(cached.read_text())
                                if previous.get("fingerprint") == fingerprint:
                                    return previous
                            return native_review(root, state, instructions, audit)
                        finally:
                            fcntl.flock(lock, fcntl.LOCK_EX)
                    try:
                        result = dispatch(root, runtime, event, audit, review)
                    finally:
                        if review_held:
                            fcntl.flock(review_lock, fcntl.LOCK_UN)
            audit("hook.dispatch.finished", hook_event=event.get("hook_event_name"), tool=event.get("tool_name"), session_id=event.get("session_id"))
            print(json.dumps(result))
        except Exception as error:
            import traceback
            audit("hook.dispatch.failed", error=str(error), stack=traceback.format_exc())
            print(f"Codex hook failed; inspect {log_path}: {error}", file=sys.stderr)
            return 2
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
